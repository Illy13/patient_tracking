package com.patient_traking;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

public class DBConnection {
    private static Connection conn;

    static {
        try {
            // H2 in-memory emulando la sintassi PostgreSQL
            String url = "jdbc:h2:mem:patientdb;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";
            conn = DriverManager.getConnection(url, "sa", "");
            System.out.println("DataBase H2 connesso con successo (In-Memory)!");
            
            // Inizializza automaticamente le tabelle di prova
            initDatabase();
        } catch (SQLException e) {
            System.out.println("Connessione fallita: " + e.getMessage());
        }
    }

    public static Connection getConn() {
        return conn;
    }

    private static void initDatabase() {
        try (Statement stmt = conn.createStatement()) {

    // ------------------------------------------------------------
            // 1. LOGIN: paziente (matricola 1001) e medico (matricola 1)
            // ------------------------------------------------------------
            stmt.execute("CREATE TABLE IF NOT EXISTS matpaz (matricola INT PRIMARY KEY, nome VARCHAR(50), cognome VARCHAR(50), passw VARCHAR(50));");
            stmt.execute("INSERT INTO matpaz (matricola, nome, cognome, passw) VALUES (1001, 'Giuseppe', 'Verdi', 'pass123');");
 
            stmt.execute("CREATE TABLE IF NOT EXISTS matmed (matricola INT PRIMARY KEY, nome VARCHAR(50), cognome VARCHAR(50), passw VARCHAR(50));");
            stmt.execute("INSERT INTO matmed (matricola, nome, cognome, passw) VALUES (1, 'Mario', 'Rossi', 'doc123');");
 
            // ------------------------------------------------------------
            // 2. PAZIENTI (tutti assegnati al medico 1)
            // ------------------------------------------------------------
            stmt.execute("CREATE TABLE IF NOT EXISTS pazienti (pid INT PRIMARY KEY, nome VARCHAR(50), cognome VARCHAR(50), med_ref INT);");
            stmt.execute("INSERT INTO pazienti (pid, nome, cognome, med_ref) VALUES " +
                    "(1001, 'Giuseppe', 'Verdi', 1), " +
                    "(1002, 'Maria', 'Bianchi', 1), " +
                    "(1003, 'Luca', 'Ferrari', 1);");
 
            // ------------------------------------------------------------
            // 3. FARMACI E TERAPIE
            // ------------------------------------------------------------
            stmt.execute("CREATE TABLE IF NOT EXISTS farmaco (fid INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(100));");
            stmt.execute("INSERT INTO farmaco (fid, nome) VALUES " +
                    "(1, 'Tachipirina 1000'), " +
                    "(2, 'Aspirina 500'), " +
                    "(3, 'Omez 20mg');");
 
            stmt.execute("CREATE TABLE IF NOT EXISTS terapia (id INT GENERATED BY DEFAULT AS IDENTITY(START WITH 10) PRIMARY KEY, mid INT, pid INT, fid INT, quantita INT, n_ass INT, indicazioni VARCHAR(255), dosaggio VARCHAR(50));");
            stmt.execute("INSERT INTO terapia (id, mid, pid, fid, quantita, n_ass, indicazioni, dosaggio) VALUES " +
                    "(1, 1, 1001, 1, 1, 3, 'Dopo i pasti', '1 compressa'), " +
                    "(2, 1, 1001, 3, 1, 1, 'Al mattino a digiuno', '1 compressa'), " +
                    "(3, 1, 1002, 2, 1, 2, 'In caso di dolore', '1 bustina');");
 
            // Terapie concomitanti (registrate dal paziente)
            stmt.execute("CREATE TABLE IF NOT EXISTS terapia_concom (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, quantita INT, pid INT, fid INT, data_inizio DATE, data_fine DATE);");
 
            // ------------------------------------------------------------
            // 4. STORICO ASSUNZIONI
            // ------------------------------------------------------------
            stmt.execute("CREATE TABLE IF NOT EXISTS assunzione (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, pid INT, fid INT, quantita INT, dataora TIMESTAMP DEFAULT CURRENT_TIMESTAMP);");
            stmt.execute("INSERT INTO assunzione (pid, fid, quantita) VALUES (1001, 1, 1), (1001, 3, 1);");
 
            // ------------------------------------------------------------
            // 5. MESSAGGI
            // ------------------------------------------------------------
            stmt.execute("CREATE TABLE IF NOT EXISTS messaggi (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, mittente VARCHAR(10), mid INT, pid INT, testo VARCHAR(500), dataora TIMESTAMP DEFAULT CURRENT_TIMESTAMP);");
            stmt.execute("INSERT INTO messaggi (mittente, mid, pid, testo) VALUES " +
                    "('p', 1, 1001, 'Buongiorno Dottore, ho preso la Tachipirina ma ho ancora un leggero fastidio.'), " +
                    "('m', 1, 1001, 'Buongiorno Giuseppe, attenda qualche ora. Se persiste mi ricontatti.');");
 
            // ------------------------------------------------------------
            // 6. FATTORI DI RISCHIO
            // ------------------------------------------------------------
            stmt.execute("CREATE TABLE IF NOT EXISTS fattore_rischio (id INT PRIMARY KEY, nome VARCHAR(100));");
            stmt.execute("INSERT INTO fattore_rischio (id, nome) VALUES (1, 'Fumatore'), (2, 'Diabete'), (3, 'Ipertensione');");
 
            stmt.execute("CREATE TABLE IF NOT EXISTS fattori_rischio_paz (pid INT, id_fattore INT);");
            stmt.execute("INSERT INTO fattori_rischio_paz (pid, id_fattore) VALUES (1001, 1), (1001, 3);");
 
            // ------------------------------------------------------------
            // 7. PATOLOGIE
            //    data_fine NULL  = patologia ancora in corso
            //    data_fine piena = patologia pregressa (guarita)
            // ------------------------------------------------------------
            stmt.execute("CREATE TABLE IF NOT EXISTS patologia (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(100));");
            stmt.execute("INSERT INTO patologia (nome) VALUES " +
                    "('Ipertensione'), " +      // id 1
                    "('Diabete di tipo 2'), " + // id 2
                    "('Gastrite'), " +          // id 3
                    "('Influenza');");          // id 4
 
            stmt.execute("CREATE TABLE IF NOT EXISTS patologie_paziente (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_patologia INT, pid INT, data_inizio DATE, data_fine DATE);");
            stmt.execute("INSERT INTO patologie_paziente (id_patologia, pid, data_inizio, data_fine) VALUES " +
                    "(1, 1001, '2022-03-15', NULL), " +          // Giuseppe: ipertensione in corso
                    "(3, 1001, '2023-06-01', NULL), " +          // Giuseppe: gastrite in corso
                    "(4, 1001, '2024-01-10', '2024-01-20'), " +  // Giuseppe: influenza pregressa
                    "(2, 1002, '2021-09-05', NULL);");           // Maria: diabete in corso
 
            // ------------------------------------------------------------
            // 8. PRESSIONE
            //    DATEADD('DAY', -5, CURRENT_TIMESTAMP) significa "5 giorni fa"
            //    Servono date recenti: i grafici mostrano solo gli ultimi giorni/mese
            // ------------------------------------------------------------
            stmt.execute("CREATE TABLE IF NOT EXISTS pressione (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, pid INT, dataora TIMESTAMP DEFAULT CURRENT_TIMESTAMP, minima INT, massima INT);");
            stmt.execute("INSERT INTO pressione (pid, dataora, minima, massima) VALUES " +
                    // ultimi 6 giorni (grafico settimanale)
                    "(1001, DATEADD('DAY', -5, CURRENT_TIMESTAMP), 80, 120), " +
                    "(1001, DATEADD('DAY', -4, CURRENT_TIMESTAMP), 82, 125), " +
                    "(1001, DATEADD('DAY', -3, CURRENT_TIMESTAMP), 85, 130), " +
                    "(1001, DATEADD('DAY', -2, CURRENT_TIMESTAMP), 78, 118), " +
                    "(1001, DATEADD('DAY', -1, CURRENT_TIMESTAMP), 80, 122), " +
                    "(1001, CURRENT_TIMESTAMP, 83, 127), " +
                    // giorni più vecchi (grafico mensile)
                    "(1001, DATEADD('DAY', -10, CURRENT_TIMESTAMP), 79, 119), " +
                    "(1001, DATEADD('DAY', -15, CURRENT_TIMESTAMP), 84, 128), " +
                    "(1001, DATEADD('DAY', -20, CURRENT_TIMESTAMP), 81, 124), " +
                    "(1001, DATEADD('DAY', -25, CURRENT_TIMESTAMP), 86, 132);");
 
            // ------------------------------------------------------------
            // 9. SINTOMI
            // ------------------------------------------------------------
            stmt.execute("CREATE TABLE IF NOT EXISTS sintomi (sid INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(100));");
            stmt.execute("INSERT INTO sintomi (nome) VALUES " +
                    "('Mal di testa'), " +  // sid 1
                    "('Nausea'), " +        // sid 2
                    "('Vertigini'), " +     // sid 3
                    "('Febbre'), " +        // sid 4
                    "('Stanchezza');");     // sid 5
 
            stmt.execute("CREATE TABLE IF NOT EXISTS registra_sintomi (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, pid INT, sid INT, info VARCHAR(255), data DATE);");
            stmt.execute("INSERT INTO registra_sintomi (pid, sid, info, data) VALUES " +
                    "(1001, 1, 'Dolore leggero alla tempia', CURRENT_DATE), " +
                    "(1001, 5, 'Dopo pranzo', DATEADD('DAY', -2, CURRENT_DATE));");

    System.out.println("Tabelle H2 create e inizializzate con successo!");
    } catch (SQLException e) {
        System.out.println("Errore durante l'inizializzazione del DB: " + e.getMessage());
    }
}

    
}
